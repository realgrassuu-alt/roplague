"""RoPlague: upload build/plague_sfx/sprite.ogg (tools/assets/make_plague_sfx.py) as ONE Audio asset with
Open Cloud and write src/shared/Assets/AudioPlague.luau (every effect a region of the sprite).

Runs with the talon-spoofer venv, whose keyring holds the Open Cloud key (sent only in its x-api-key
header, never printed):

    C:/Users/PC/Desktop/talon-spoofer/.venv/Scripts/python.exe tools/assets/upload_plague_sfx.py [--user ID]
"""

import argparse
import asyncio
import json
import os
import sys

sys.path.insert(0, r"C:\Users\PC\Desktop\talon-spoofer\src")
from talon_spoofer.core.auth import AuthBundle  # noqa: E402
from talon_spoofer.core.client import RobloxClient  # noqa: E402

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
SPRITE = os.path.join(REPO, "build", "plague_sfx", "sprite.ogg")
INDEX = os.path.join(REPO, "build", "plague_sfx", "sprite.json")
OUT = os.path.join(REPO, "src", "shared", "Assets", "AudioPlague.luau")
ASSETS = "https://apis.roblox.com/assets/v1/assets"
OP = "https://apis.roblox.com/assets/v1/operations/{}"


async def upload(user_id: int) -> int:
    payload = {
        "assetType": "Audio",
        "displayName": "RoPlague sound effects",
        "description": "RoPlague interface and game sounds, made from scratch",
        "creationContext": {"creator": {"userId": str(user_id)}},
    }
    data = open(SPRITE, "rb").read()
    async with RobloxClient(AuthBundle.from_keyring(), timeout=180.0) as c:
        files = {
            "request": (None, json.dumps(payload), "application/json"),
            "fileContent": ("roplague_sfx.ogg", data, "audio/ogg"),
        }
        op = await c.request_json("POST", ASSETS, auth_mode="api_key", files=files)
        path = op.get("path") if isinstance(op, dict) else None
        if not path:
            raise SystemExit("upload returned no operation: %r" % (op,))
        oid = path.split("/")[-1]
        for _ in range(120):
            st = await c.request_json("GET", OP.format(oid), auth_mode="api_key")
            if isinstance(st, dict) and st.get("done"):
                aid = (st.get("response") or {}).get("assetId")
                if aid:
                    return int(aid)
                raise SystemExit("upload failed: %r" % (st.get("error"),))
            await asyncio.sleep(3)
    raise SystemExit("upload timed out")


def write_manifest(asset_id: int):
    idx = json.load(open(INDEX))
    lines = [
        "-- GENERATED by tools/assets/upload_plague_sfx.py — do not edit by hand.",
        "-- RoPlague's own sound effects (tools/assets/make_plague_sfx.py: synthesised, no samples), all in",
        "-- one audio sprite; every entry is a region of it. AudioDirector merges these over every other",
        "-- sound table, so nothing of the original developer's is played.",
        "return {",
        "\tsfx = {",
    ]
    for name in sorted(idx):
        a, b, ln = idx[name]
        lines.append('\t\t%s = { sprite = "rbxassetid://%d", start = %s, stop = %s, length = %s },' % (name, asset_id, a, b, ln))
    lines += ["\t},", "}", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", type=int, default=3007483)
    ap.add_argument("--asset", type=int, default=0, help="skip the upload, write the manifest for this id")
    a = ap.parse_args()
    aid = a.asset or asyncio.run(upload(a.user))
    write_manifest(aid)
    print("asset", aid, "->", os.path.relpath(OUT, REPO))


if __name__ == "__main__":
    main()
